<h2><span class="mw-headline" id="Resource_usage">Resource usage</span></h2>
<p>A server requires very little resources, a $5 VPS from <a rel="nofollow" class="external text" href="https://www.digitalocean.com/?refcode=c053cdfd84c5">Digital Ocean</a> can easily run a few hundred players.
The main bottlenecks are usually (in order): bandwidth, CPU, uplink, memory and diskspace. For more hosts, please check out our <a href="/Server/Hosts" title="Server/Hosts">Server Hosts</a> page.
</p>
<h3><span class="mw-headline" id="Bandwidth_and_network_usage">Bandwidth and network usage</span></h3>
<p>While this greatly depends on scripts and sync rates, generally 100 players will use 5 mbit up and 1 mbit down.
This means a server with 100 players consistently throughout the entire month uses 2 TB of bandwidth.
</p>
<h3><span class="mw-headline" id="CPU_Usage">CPU Usage</span></h3>
<p>This again greatly depends on scripts and sync rates, a server with a few light scripts will use about 10% of an i5 CPU at 3.10 GHz.
Most servers however will be running huge scripts so it entirely depends on the scripts and their optimisation.
</p>
<h3><span class="mw-headline" id="Memory_and_disk_usage">Memory and disk usage</span></h3>
<p>This entirely depends upon your scripts and log file. The server without any scripts or log file uses around 30 MB of disk space and 40 MB of RAM.
</p>
<h2><span class="mw-headline" id="Beta_tests">Beta tests</span></h2>
<p>We ran the final beta test on a dedicated server with the following specifications:
</p>
<ul>
<li> Intel(R) Core(TM) i5-3570S CPU
</li>
<li> 4 cores at 3.10 GHz
</li>
<li> 8 GB of RAM
</li>
<li> 2x 1 TB at 7200 rpm in software RAID 1
</li>
<li> 100 mbit full-duplex
</li>
</ul>
<p>Please note that most of this was not necessary, on average the server used:
</p>
<ul>
<li> 1-2 full cores
</li>
<li> 400 MB of memory
</li>
<li> 250 MB of disk space
</li>
<li> 50 mbit up, 10 mbit down
</li>
</ul>

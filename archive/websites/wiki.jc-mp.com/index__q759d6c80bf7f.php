<h2><span class="mw-headline" id="0.3_-_2017_May_28">0.3 - 2017 May 28</span></h2>
<h4><span class="mw-headline" id="New_Features">New Features</span></h4>
<ul>
<li>Client
<ul>
<li>Added Roads class, allowing scripters to use global road pathfinding
</li>
<li>Added ClientActor:FindShortestPath for utilizing NPC point-to-point pathfinding
</li>
<li>Added Vehicle:SetSeatLocked and Vehicle:GetSeatLocked for (un)locking specific vehicle seats
</li>
<li>Added GameRenderOpaque event for rendering non-transparent items to benefit from post effects, such as the water ripple effect
</li>
<li>Added LocalPlayer:GetAimMode and the AimMode enum
</li>
<li>Added Chat:Get/SetPosition and Chat:ResetPosition
</li>
<li>Added TraverseType, RoadType and SpeedLimit enums
</li>
</ul>
</li>
<li>Shared
<ul>
<li>Added ModuleError event for handling errors caused by client/server Lua modules
</li>
<li>Added Vector2/3:Reflect as an alias for static functions Vector2/3.Reflect
</li>
</ul>
</li>
</ul>
<h4><span class="mw-headline" id="Bug_fixes_and_changes">Bug fixes and changes</span></h4>
<ul>
<li> Client
<ul>
<li>Fixed an issue where a player could enter an occupied stunt cling position, resulting in a crash for each streamed-in player
</li>
<li>Refactored renderer to properly adhere to the Just Cause 2 threading model
</li>
<li>Text renderer will now re-use buffers whenever possible to improve performance
</li>
<li>Fixed a bug with first main menu background not being resized to fit on the screen
</li>
<li>Vehicle:GetDriver and Vehicle:GetOccupants will now return and include ClientActors <b>(Breaking change)</b>
</li>
</ul>
</li>
<li>Shared
<ul>
<li>Fixed an issue where attempting to steal Tuk-Tuk or an ATV could result in the hijacker getting stuck in a bugged state
</li>
<li>StaticObjects with the `fixed` flag set to false will now properly simulate rotation
</li>
</ul>
</li>
</ul>
<h2><span class="mw-headline" id="0.2.3_-_2016_October_23">0.2.3 - 2016 October 23</span></h2>
<h4><span class="mw-headline" id="New_Features_2">New Features</span></h4>
<ul>
<li>Client
<ul>
<li>Added EntityBulletHit event that triggers when the local player hits a Player or NPC with a bullet
</li>
<li>LocalPlayerExitVehicle now fires when the player's vehicle is removed while they were in it
</li>
<li>Added GetOutlineEnabled, SetOutlineEnabled, and SetOutlineColor to Characters and StaticObjects
</li>
</ul>
</li>
<li>Shared
<ul>
<li>Changed Firestarter achievement to require 1,000 kills instead of 3,000
</li>
<li>Changed Only Human achievement to spread virally. If you kill a player who has the achievement, you will also be granted it
</li>
</ul>
</li>
</ul>
<h4><span class="mw-headline" id="Bug_fixes_and_changes_2">Bug fixes and changes</span></h4>
<ul>
<li> Client
<ul>
<li>Hopefully fixed the crashes that have plagued AMD users for many months. We have reported a solution and details surrounding the bug to AMD
</li>
<li>Fixed a bug on AMD cards where SSAO would cause rendering artifacts. It has now been re-enabled in the options window
</li>
<li>Fixed a bug where vehicle mounted guns rotation could become mirrored
</li>
<li>Fixed one of the most frequently encountered crashes relating to decals. It should now be safe to enable decals again!
</li>
<li>Removed unsynced sentry turrets and cannons from the game
</li>
<li>Fixed a bug where a player would become stuck on a bike if they attempted to steal it while the driver was reversing
</li>
<li>Fixed a bug where vehicles could become invulnerable if repaired while about to explode
</li>
<li>Fixed a bug where certain bushes could crash the game when collided with as they lacked a collision mesh
</li>
<li>Fixed a bug where RakNet was unintentionally creating a listen socket on port 80
</li>
</ul>
</li>
</ul>

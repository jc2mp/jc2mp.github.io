<h2> <span class="mw-headline" id="General_FAQ"> General FAQ </span></h2>
<h5> <span class="mw-headline" id="Where_can_I_download_JC2-MP.3F"> Where can I download JC2-MP? </span></h5>
<p>JC2-MP is currently not released and the final versions of the client or server are not released yet.
</p><p>If there is a public beta currently running, you can find the latest version of JC2-MP on our website. You must be logged into the forum in order to download and play.
</p>
<h5> <span class="mw-headline" id="When_is_the_next_public_beta.3F.2FHow_can_I_keep_up_to_date.3F"> When is the next public beta?/How can I keep up to date? </span></h5>
<p>If there is a beta test coming up, it will be announced and a countdown clock will be on every page of the website. If there is no countdown clock, there is no test currently running and there is no future time/date known for the next test.
</p><p>There is nothing more specific, so please do not ask.
</p>
<h5> <span class="mw-headline" id="Where_are_upcoming_public_beta_tests_announced.3F"> Where are upcoming public beta tests announced? </span></h5>
<p>Public betas are announced on our <a rel="nofollow" class="external text" href="https://twitter.com/jc2mpdev">Twitter</a>, <a rel="nofollow" class="external text" href="http://www.facebook.com/jc2mp">Facebook</a>, <a rel="nofollow" class="external text" href="http://www.jc-mp.com/irc">IRC</a>, <a rel="nofollow" class="external text" href="http://steamcommunity.com/groups/JC2-MP">Steam group</a> and all pages of our <a rel="nofollow" class="external text" href="http://www.jc-mp.com">website</a> and <a rel="nofollow" class="external text" href="http://www.jc-mp.com/forums">forums</a>.
</p>
<h5> <span class="mw-headline" id="How_can_I_participate_in_a_public_beta_test.3F"> How can I participate in a public beta test? </span></h5>
<p>You can only join the beta server when there is a public beta test going on.
</p><p>If there is a public test running, it will be shown on the website. Please use the server browser to join the public test server: <a rel="nofollow" class="external free" href="https://www.jc-mp.com/servers/">https://www.jc-mp.com/servers/</a>
</p>
<h5> <span class="mw-headline" id="When_was_the_last_JC2-MP_test.3F"> When was the last JC2-MP test? </span></h5>
<p>You can find the history of JC2-MP tests <a href="/index.php/Test_History" title="Test History">here</a>.
</p>
<h5> <span class="mw-headline" id="What_version_of_the_game_do_I_need.2FAre_pirated_copies_supported.2FDoes_the_demo_work.3F"> What version of the game do I need/Are pirated copies supported/Does the demo work? </span></h5>
<p>Only the purchased Steam version is supported.
</p><p>Please see <a href="/index.php/Game_Version" title="Game Version">this page</a> for more information.
</p>
<h5> <span class="mw-headline" id="When_will_JC2-MP_be_released.3F"> When will JC2-MP be released? </span></h5>
<p>The future. There is nothing more specific, so please do not ask.
</p>
<h5> <span class="mw-headline" id="Why_do_you_shut_down_the_server_when_testing_is_over.3F"> Why do you shut down the server when testing is over? </span></h5>
<p>Because we are holding controlled tests and JC2-MP is not released yet.
</p><p>We only test when we believe that we have fixed an indeterminate number of bugs and we stop testing when we have found enough bugs to work on.
</p>
<h5> <span class="mw-headline" id="Can_I_change_my_model.3F"> Can I change my model? </span></h5>
<p>The Lua API gives server owners the ability to change models using scripts.
</p><p>For the public test, press B to open the buy menu to purchase character models using money earned in-game.
</p>
<h5> <span class="mw-headline" id="Are_there_AI_.2F_NPCs.3F"> Are there AI / NPCs? </span></h5>
<p>No. Very unlikely to be added, at least not in the same sense as singleplayer.
</p>
<h5> <span class="mw-headline" id="Will_64_or_32-bit_installs_work.3F"> Will 64 or 32-bit installs work? </span></h5>
<p>Yes. It makes no difference.
</p>
<h5> <span class="mw-headline" id="Does_this_work_on_PS3.2FXbox_360.3F"> Does this work on PS3/Xbox 360? </span></h5>
<p>No, and it won't. Ever.
</p>
<h5> <span class="mw-headline" id="Do_I_need_a_copy_of_Just_Cause_2.3F"> Do I need a copy of Just Cause 2? </span></h5>
<p>Yes, this is a modification and hence does not include the game.
</p>
<h5> <span class="mw-headline" id="Will_JC2-MP_affect_my_single-player_game.3F"> Will JC2-MP affect my single-player game? </span></h5>
<p>No, the mod does not affect your game saves in any way.
</p>
<h5> <span class="mw-headline" id="Is_the_JC2-MP_team_accepting_donations.3F"> Is the JC2-MP team accepting donations? </span></h5>
<p>Yes, we are currently accepting donations to cover hosting costs. <a rel="nofollow" class="external text" href="https://www.jc-mp.com/donate/">You can donate here.</a>
</p>
<h5> <span class="mw-headline" id="Is_JC2-MP_free_to_play.3F"> Is JC2-MP free to play? </span></h5>
<p>Yes, the mod is completely free to download and play.
</p>

</p>
<h3> <span class="mw-headline" id="Spawning"> Spawning </span></h3>
<h5> <span class="mw-headline" id="Can_I_spawn_vehicles.3F_Weapons.3F_etc..."> Can I spawn vehicles? Weapons? etc... </span></h5>
<p>This is up to server owners.
</p><p>In our public beta tests, and with the default scripts, vehicles spawn in specific locations. Weapons are given to you when you spawn. We are also running a buy menu script. It allows you to purchase vehicles, weapons, and skins with money you earn through play.
</p>
<h5> <span class="mw-headline" id="How_often_do_vehicles_respawn.3F"> How often do vehicles respawn? </span></h5>
<p>By default, vehicles respawn after 45 seconds of unuse. If a vehicle explodes, it will respawn within 8 seconds. These can be changed in the server config.
</p><p>It is also worth noting that vehicles can only be damaged when there's a player driving them.
</p>
<h5> <span class="mw-headline" id="Can_I_access_the_black_market.3F"> Can I access the black market? </span></h5>
<p>No. The black market from singleplayer will not be in the mod. Its functionality will be scriptable using Lua. In fact, the buy menu running during the public tests is a perfect example of a black market replacement.
</p>
<h3> <span class="mw-headline" id="Location_of_common_landmarks"> Location of common landmarks </span></h3>
<h5> <span class="mw-headline" id="Where_is_Panau_International_Airport.3F"> Where is Panau International Airport? </span></h5>
<p>East of Panau City, at approximately 10000, 13000. You can also go there using <i>/tp airport</i>.
</p>
<h5> <span class="mw-headline" id="Where_is_the_race_track.3F"> Where is the race track? </span></h5>
<p>North-east of Panau City, or north of Panau International Airport, at approximately 9500,11200. You can also go there using <i>/tp racetrack</i>.
</p>
<h5> <span class="mw-headline" id="Where_is_the_Mile_High_Club.3F"> Where is the Mile High Club? </span></h5>
<p>It's in the north-east-east region of the map, at approximately 29000,11000. You can also go there using <i>/tp mhc</i>.
</p>
<h2> <span class="mw-headline" id="Server_Hosting_FAQ"> Server Hosting FAQ </span></h2>
<h5> <span class="mw-headline" id="Can_I_host_my_own_server.3F"> Can I host my own server? </span></h5>
<p>No, the server software is not available to the public at this time.
It will be released when JC2-MP itself has been released.
</p>
<h5> <span class="mw-headline" id="Will_there_be_a_Linux_build_of_the_server.3F"> Will there be a Linux build of the server? </span></h5>
<p>Yes, there are both Windows and Linux builds of the server.
</p>
<h5> <span class="mw-headline" id="Will_the_server_support_scripting.3F"> Will the server support scripting? </span></h5>
<p>Yes, the server will provide a scripting interface using the Lua language.
</p>
<h5> <span class="mw-headline" id="Can_LAN-only_servers_be_hosted.3F"> Can LAN-only servers be hosted? </span></h5>
<p>Yes, servers can be hosted fine on a LAN. Unless your server is exposed to the internet, then it is already LAN-only.
</p>
<h5> <span class="mw-headline" id="How_does_the_server_handle_DLC.3F"> How does the server handle DLC? </span></h5>
<p>The server will be able to require or disable any DLC for all players. During public betas, all DLC is disabled.
</p>
<h5> <span class="mw-headline" id="When_will_the_server_be_released.3F"> When will the server be released? </span></h5>
<p>At the same time as when JC2-MP is released.
</p>
<h5> <span class="mw-headline" id="Which_resources_does_the_server_need.3F"> Which resources does the server need? </span></h5>
<p>We have previously measured that the server, with 1000 players concurrently playing, used 2 CPU cores (2.93 GHz), 90 MB of RAM, 5 MB of disk space and 35 mbit per second.
</p><p>We are working on improving the CPU usage and try to further optimize the bandwidth usage to make sure they are reasonable.
</p>

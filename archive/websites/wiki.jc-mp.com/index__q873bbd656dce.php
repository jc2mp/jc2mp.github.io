<h4><span class="mw-headline" id="Features:">Features:</span></h4>
<ul>
<li> Scripting system using the simple but powerful Lua language. Use server-side and client-side scripts to create anything from a spawn menu to entire gamemodes. For more information <a rel="nofollow" class="external text" href="https://wiki.jc-mp.com/Lua">click here</a>
</li>
<li> Server browser allows you to easily find a server and keep track of your favorites.
</li>
<li> Steam authentication: your JC2-MP account is tied to your steam account, which allows servers to keep track of players by Steam ID.
</li>
<li> An optimised network streamer means a server can support thousands of players and vehicles across Panau.
</li>
</ul>
<p><br />
</p>
<h4><span class="mw-headline" id="Synchronization">Synchronization</span></h4>
<p>With synchronization we mean that some of your actions might not show on another players screen. For example "grapple hook is not synced" means that if I use the grapple hook on my screen other players will not see the grapple hook.
</p>
<h4><span class="mw-headline" id="What_is_synced.3F">What is synced?</span></h4>
<ul>
<li> On-foot movement
</li>
<li> On-foot weapons
</li>
<li> Vehicle movement
</li>
<li> Vehicle weapons
</li>
<li> Vehicle mounted weapons (such as turrets in jeeps)
</li>
<li> Vehicle spawns
</li>
<li> Vehicle colors
</li>
<li> Vehicle damage
</li>
<li> Stunt position
</li>
<li> Time
</li>
<li> Weather
</li>
<li> Character models
</li>
<li> Parachute
</li>
</ul>
<h4><span class="mw-headline" id="What_is_not_synced.3F">What is not synced?</span></h4>
<ul>
<li> Fixed Mounted Guns (Cannon / Flak Cannon / Fixed Mini-Gun)
</li>
<li> Grappling hook
</li>
<li> Persistent destroyed structures
</li>
<li> Unoccupied vehicles
</li>
<li> Thrown explosives and melee
</li>
<li> Dual wielding
</li>
</ul>
<p><br />
<i>As JC2-MP is in development, you can expect this list to change</i>.
</p>


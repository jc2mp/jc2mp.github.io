<h4><span class="mw-headline" id="Can_I_spawn_objects_other_than_vehicles_and_checkpoints.3F">Can I spawn objects other than vehicles and checkpoints?</span></h4>
<p>Yes! Have a look at <a href="/Lua/Server/StaticObject" title="Lua/Server/StaticObject">StaticObject</a>.
</p>
<h4><span class="mw-headline" id="How_do_I_draw_custom_images.3F">How do I draw custom images?</span></h4>
<p>The most common method is to use Image.Create(AssetLocation.Base64, "&lt;base64 string&gt;").
</p><p>There is an <i>images</i> directory on the client, you can load any images in there with <a href="/Lua/Client/Image/Static_Functions/Create" title="Lua/Client/Image/Static Functions/Create">Image.Create</a>. I.e. for <i>images/horse.jpg</i>, the path for Image.Create would be <i>horse.jpg</i>.
</p><p>You can also use .zip files and a <i>dropzone</i> directory. (This is <b>not</b> Just Cause 2's dropzone.) Modules can only use the .zip file with their name. I.e. for <i>dropzone/MyModule.zip/images/horse.jpg</i>, the path for Image.Create would be <i>horse.jpg</i>
</p>
<h4><span class="mw-headline" id="Is_it_possible_to_stream_images_to_clients_automatically.3F">Is it possible to stream images to clients automatically?</span></h4>
<p>Yes! Though they must be converted into base64 first. See the <a rel="nofollow" class="external text" href="https://wiki.jc-mp.com/Lua/Client/Image/Static_Functions/Create">Image.Create Documentation</a>. We plan on adding Steam Workshop support in a later release, which will allow clients to automatically download assets.
</p>
<h4><span class="mw-headline" id="Can_chat_messages_have_multiple_colors.3F">Can chat messages have multiple colors?</span></h4>
<p>No, the default chat system currently only supports one color for custom messages.
</p>
<h4><span class="mw-headline" id="Can_vehicle_handling_be_changed.3F">Can vehicle handling be changed?</span></h4>
<p>You cannot do what singleplayer mods can, such as change the top speed to whatever you want. However, for agency vehicles, you can set their upgrades by setting their template. (See <a href="/Lua/Server/Vehicle/Static_Functions/Create" title="Lua/Server/Vehicle/Static Functions/Create">Vehicle.Create</a>) Agency vehicles are the ones that you can spawn in singleplayer, such as the Silverbolt and Traver-Z.
</p><p>Most agency vehicles take the following vehicle templates:
</p>
<ul>
<li> Default
</li>
<li> WeaponUpgrade0
</li>
<li> WeaponUpgrade1
</li>
<li> FullyUpgraded
</li>
</ul>
<p><i>Note: WeaponUpgrade0/WeaponUpgrade1 still upgrade the handling, even if the weapon doesn't change.</i>
</p>
<h4><span class="mw-headline" id="Can_weapon_stats_be_changed.3F">Can weapon stats be changed?</span></h4>
<p>No, not currently.
</p>
<h4><span class="mw-headline" id="What_unit_of_distance_does_the_game_use.3F">What unit of distance does the game use?</span></h4>
<p>Everything uses meters.
</p>
<h4><span class="mw-headline" id="Does_the_API_use_degrees_or_radians.3F">Does the API use degrees or radians?</span></h4>
<p>Everything uses radians. You can use the Lua functions <i>math.rad(degrees)</i> and <i>math.deg(radians)</i> to convert numbers between the two. If you want the string representation of an Angle in degrees, you can use <a href="/Lua/Shared/Angle/Functions/DegreesString" title="Lua/Shared/Angle/Functions/DegreesString">Angle:DegreesString</a>.
</p>
<h4><span class="mw-headline" id="I_don.27t_know_how_to_compile_lua_modules.2C_do_you_have_any_redistributables.3F">I don't know how to compile lua modules, do you have any redistributables?</span></h4>
<p>Yes, a list can be found <a href="/Lua/Third_Party_Modules" title="Lua/Third Party Modules">here</a>.
</p>



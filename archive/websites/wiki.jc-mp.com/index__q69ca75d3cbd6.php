<h2><span class="mw-headline" id="Server_hosts">Server hosts</span></h2>
<p>This page will list hosts that you can use for JC2-MP hosting. Please note this is merely a list, we do not vouch for any of these hosts.
</p>
<h4><span class="mw-headline" id="How_to_add_a_host">How to add a host</span></h4>
<p>Simply login into this wiki by using the "Click here to login with your JC2-MP account" link at the right top and edit this page. If you offer both gameservers and VPSes / Dedicated servers, you can add your host to both tables. Please do not remove any hosts you do not know, open a forum topic to do this instead. Hosts need to at least have a website and fixed pricing to be listed here. Using any referral URLs is not allowed unless it goes to JC2-MP to cover our server costs. <b>The server hosts are sorted by alphabetical order, so add your host at the correct place in the table. Please use preview to make sure it looks properly before saving.</b>
</p>
<h2><span class="mw-headline" id="Gameserver_hosts">Gameserver hosts</span></h2>
<p>The hosts listed here offer gameserver hosting, which means they manage the servers and run the JC2-MP server for you. This means you do not have to worry about the servers, networking, firewalls, updates and generally get access to a control panel that allows you to easily manage your JC2-MP server. Please note that the features listed previously are usually the case but not guaranteed, contact a host if you want to make sure about certain features you need.

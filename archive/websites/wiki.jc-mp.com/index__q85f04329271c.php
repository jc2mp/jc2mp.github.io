<h2><span class="mw-headline" id="0.1.4a_-_2014_June_21">0.1.4a - 2014 June 21</span></h2>
<h4><span class="mw-headline" id="New_features_2">New features</span></h4>
<ul>
<li> Shared
<ul>
<li> Overhauled the logging system to support unicode (the first of many unicode additions to come)
</li>
<li> Added console command for profiling Lua modules; usage: profiler_sample <span style="color:#505050;font-size:80%">number_of_seconds</span>
</li>
<li> Added Color == Color operator
</li>
<li> Added IsNaN methods to Vector2/Vector3/Angle and a general purpose IsNaN function
</li>
</ul>
</li>
</ul>
<ul>
<li> Server
<ul>
<li> Added <a href="/Lua/Server/SQL/Functions/GetLastInsertId" title="Lua/Server/SQL/Functions/GetLastInsertId">SQL:GetLastInsertId</a>
</li>
</ul>
</li>
</ul>
<ul>
<li> Client
<ul>
<li> Added <a href="/Lua/Shared/AssetLocation" title="Lua/Shared/AssetLocation">AssetLocation</a>.Base64, which enables images to be loaded from Base64 strings as a temporary solution until Steam Workshop is integrated
</li>
<li> Added <a href="/Lua/Client/ClientParticleSystem" title="Lua/Client/ClientParticleSystem">ClientParticleSystem</a>
</li>
<li> Added <a href="/Lua/Client/ClientLight" title="Lua/Client/ClientLight">ClientLight</a>
</li>
<li> Added <span style="color:#505050;font-size:80%">timeout</span> parameter to <a href="/Lua/Client/ClientSound/Static_Functions/Play" title="Lua/Client/ClientSound/Static Functions/Play">ClientSound.Play</a> and <a href="/Lua/Client/ClientEffect/Static_Functions/Play" title="Lua/Client/ClientEffect/Static Functions/Play">ClientEffect.Play</a>
</li>
<li> Added <a href="/Lua/Client/LocalPlayer/Functions/IsTeleporting" title="Lua/Client/LocalPlayer/Functions/IsTeleporting">LocalPlayer:IsTeleporting</a>
</li>
<li> Added <a href="/Lua/Client/Input/Functions/Clear" title="Lua/Client/Input/Functions/Clear">Input:Clear</a>
</li>
</ul>
</li>
</ul>
<h4><span class="mw-headline" id="Bug_fixes_2">Bug fixes</span></h4>
<ul>
<li> Server
<ul>
<li> Reverted changes to SQL which were causing massive memory leaks
<ul>
<li> Note: This change was made before release to prevent server crashes related to SQL errors. If you encounter an SQL error which then crashes the server some time later, please report it.
</li>
</ul>
</li>
<li> Fixed Vector2() and Vector3() returning uninitialized data on linux
</li>
</ul>
</li>
</ul>
<ul>
<li> Client
<ul>
<li> Fixed StaticObject related crash
</li>
<li> Fixed <a href="/Lua/Server/Vehicle/Functions/SetColors" title="Lua/Server/Vehicle/Functions/SetColors">Vehicle:SetColors</a> to properly support mounted guns and ailerons
</li>
<li> Fixed Game:GetState returning 0 for menu and loading screen
</li>
<li> Fixed ClientEntity:GetId not being exposed
</li>
<li> Fixed <a href="/Lua/Client/Action" title="Lua/Client/Action">Action</a> enum name capitalization (added GuiPDAZoomOut and HeliAIAutoRoll)
</li>
<li> GWEN: Fixed crash when unsubscribing from current event
</li>
<li> GWEN: Removing the active TabButton will now select another available tab
</li>
<li> GWEN: Fixed BaseWindow's Blur event not always being called
</li>
<li> GWEN: Fixed crash when using GroupBox:RemoveAllChildren
</li>
<li> GWEN: BaseWindow functions GetNumChildren, GetChildren, and RemoveAllChildren now only act on user-created controls
</li>
</ul>
</li>
</ul>

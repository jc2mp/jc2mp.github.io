<h2><span class="mw-headline" id="General_FAQ">General FAQ</span></h2>
<h5><span class="mw-headline" id="What_version_of_the_game_do_I_need_to_play_the_mod.3F">What version of the game do I need to play the mod?</span></h5>
<p>Only the purchased Steam version is supported.
</p><p>Please see <a href="/Game_Version" title="Game Version">this page</a> for more information.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Are_pirated_copies_supported.3F">Are pirated copies supported?</span></h5>
<p>No, pirated copies are not supported.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Does_the_demo_work.3F">Does the demo work?</span></h5>
<p>No you can not play the mod with the Just Cause 2 demo.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Are_there_AI_.2F_NPCs.3F">Are there AI / NPCs?</span></h5>
<p>No, and they are very unlikely to be added, at least not in the same sense as singleplayer.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Will_64_or_32-bit_installs_work.3F">Will 64 or 32-bit installs work?</span></h5>
<p>Yes. It makes no difference.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Does_this_work_on_PS3.2FXbox_360.3F">Does this work on PS3/Xbox 360?</span></h5>
<p>No, and it won't. Ever.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Will_JC2-MP_affect_my_single-player_game.3F">Will JC2-MP affect my single-player game?</span></h5>
<p>No, the mod does not affect your game saves in any way.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Is_JC2-MP_free_to_play.3F">Is JC2-MP free to play?</span></h5>
<p>Yes, the mod is completely free to download and play.
</p><p><br />
</p>
<h5><span class="mw-headline" id="How_do_you_chat.3F">How do you chat?</span></h5>
<p>Press 'T'.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Can_I_use_mods_while_playing_JC2-MP.3F">Can I use mods while playing JC2-MP?</span></h5>
<p>Please refer to <a href="/JC2MP_Mods" title="JC2MP Mods">this page</a> for more information.
</p><p><br />
</p>
<h5><span class="mw-headline" id="How_do_I_open_the_map.3F">How do I open the map?</span></h5>
<p>Press F1.
</p><p><br />
</p>
<h5><span class="mw-headline" id="How_do_I_hide_the_chat.3F">How do I hide the chat?</span></h5>
<p>Press F3.
</p><p><br />
</p>
<h5><span class="mw-headline" id="How_often_do_vehicles_respawn.3F">How often do vehicles respawn?</span></h5>
<p>By default, vehicles respawn after 45 seconds of unuse. If a vehicle explodes, it will respawn within 8 seconds. These can be changed in the server config.
</p><p>It is also worth noting that vehicles can only be damaged when there's a player driving them.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Can_I_access_the_black_market.3F">Can I access the black market?</span></h5>
<p>No. The black market from singleplayer will not be in the mod. Its functionality will be scriptable using Lua.
</p><p>In fact, <a rel="nofollow" class="external text" href="https://github.com/Philpax/jc2mp-buymenu">the buy menu script</a> is a perfect example of a black market replacement.
</p><p><br />
</p>
<h5><span class="mw-headline" id="Is_the_JC2-MP_team_accepting_donations.3F">Is the JC2-MP team accepting donations?</span></h5>
<p>Yes, we are currently accepting donations to cover hosting costs. <a rel="nofollow" class="external text" href="https://www.jc-mp.com/donate/">You can donate here.</a>
</p>
<h2><span class="mw-headline" id="Server_Hosting_FAQ">Server Hosting FAQ</span></h2>
<h5><span class="mw-headline" id="Can_LAN-only_servers_be_hosted.3F">Can LAN-only servers be hosted?</span></h5>
<p>Yes, servers can be hosted fine on a LAN. Unless your server is exposed to the internet, then it is already LAN-only.
</p><p>Note that there is currently an issue with the LAN tab on the in-game server browser.
</p>
<h5><span class="mw-headline" id="How_do_servers_handle_DLC.3F">How do servers handle DLC?</span></h5>
<p>It is up to servers whether to require players to own DLC.
</p>
<h5><span class="mw-headline" id="Which_resources_does_the_server_need.3F">Which resources does the server need?</span></h5>
<p>Please see <a href="/Server/Requirements" title="Server/Requirements">this page</a> for more information.
</p>


		<title>Feature Overview</title>
		<link rel="alternate" type="text/html" href="https://wiki.jc-mp.com/Feature_Overview"/>
				<updated>2013-12-20T15:21:01Z</updated>
		
		<summary type="html">&lt;p&gt;RedCat: &lt;/p&gt;
&lt;hr /&gt;
&lt;div&gt;====Features:====&lt;br /&gt;
* Scripting system using the simple but powerful Lua language. Use server-side and client-side scripts to create anything from a spawn menu to entire gamemodes. For more information [http://wiki.jc-mp.com/Lua click here]&lt;br /&gt;
* Server browser allows you to easily find a server and keep track of your favorites.&lt;br /&gt;
* Steam authentication: your JC2-MP account is tied to your steam account, which allows servers to keep track of players by Steam ID.&lt;br /&gt;
* An optimised network streamer means a server can support thousands of players and vehicles across Panau.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
====Synchronization====&lt;br /&gt;
With synchronization we mean that some of your actions might not show on another players screen. For example &amp;quot;grapple hook is not synced&amp;quot; means that if I use the grapple hook on my screen other players will not see the grapple hook. &lt;br /&gt;
&lt;br /&gt;
====What is synced?====&lt;br /&gt;
&lt;br /&gt;
* On-foot movement&lt;br /&gt;
* On-foot weapons&lt;br /&gt;
* Vehicle movement&lt;br /&gt;
* Vehicle weapons&lt;br /&gt;
* Vehicle mounted weapons (such as turrets in jeeps)&lt;br /&gt;
* Vehicle spawns&lt;br /&gt;
* Vehicle colors&lt;br /&gt;
* Vehicle damage&lt;br /&gt;
* Stunt position&lt;br /&gt;
* Time&lt;br /&gt;
* Weather&lt;br /&gt;
* Character models&lt;br /&gt;
* Parachute&lt;br /&gt;
&lt;br /&gt;
====What is not synced?====&lt;br /&gt;
&lt;br /&gt;
* Fixed Mounted Guns (Cannon / Flak Cannon / Fixed Mini-Gun)&lt;br /&gt;
* Grappling hook&lt;br /&gt;
* Persistent destroyed structures&lt;br /&gt;
* Unoccupied vehicles&lt;br /&gt;
* Thrown explosives and melee&lt;br /&gt;
* Dual wielding&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
''As JC2-MP is in development, you can expect this list to change''.&lt;/div&gt;</summary>

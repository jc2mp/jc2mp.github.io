&lt;br /&gt;
&lt;br /&gt;
To stop the server and kill the screen type:&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
screen -S jcmp -X quit&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;

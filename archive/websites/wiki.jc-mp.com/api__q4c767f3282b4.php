&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
==Downloading SteamCMD==&lt;br /&gt;
First we need to download SteamCMD. For more information on SteamCMD please [https://developer.valvesoftware.com/wiki/SteamCMD click here]&lt;br /&gt;
&lt;br /&gt;
Login to your server with SSH, then head over to the home directory, we will make our Steam folder there.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
cd /home&lt;br /&gt;
mkdir steam&lt;br /&gt;
cd steam&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
Now we can download SteamCMD and unpack it.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
wget http://media.steampowered.com/client/steamcmd_linux.tar.gz&lt;br /&gt;
tar -xvzf steamcmd_linux.tar.gz&lt;br /&gt;
rm steamcmd_linux.tar.gz&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
==Running SteamCMD and downloading the server==&lt;br /&gt;
Now we need to run SteamCMD.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
./steamcmd.sh&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
SteamCMD will now update and it might download some files, wait till it finishes.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
Now let's download the latest server version!&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
force_install_dir ./jcmp&lt;br /&gt;
app_update 261140&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
It will now download the latest server version. Once it is done downloading we can safely exit SteamCMD.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
quit&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
==Changing the server options==&lt;br /&gt;
First lets move to the JC2-MP server directory.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
cd jcmp&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
Now use your favorite editor to edit the server's configuration file, I personally use nano.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
nano config.lua&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;

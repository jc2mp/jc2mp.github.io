nano config.lua&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
Every possible server option is explained in the configuration file. Simply follow the instructions.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
==Starting up the server in screen==&lt;br /&gt;

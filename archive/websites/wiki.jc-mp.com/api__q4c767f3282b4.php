===== Can I use mods while playing JC2-MP? =====&lt;br /&gt;
&lt;br /&gt;
Please refer to [[JC2MP_Mods|this page]] for more information.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== How do I open the map? =====&lt;br /&gt;
&lt;br /&gt;
Press F1.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== How do I hide the chat? =====&lt;br /&gt;
&lt;br /&gt;
Press F3.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== How often do vehicles respawn? =====&lt;br /&gt;
&lt;br /&gt;
By default, vehicles respawn after 45 seconds of unuse. If a vehicle explodes, it will respawn within 8 seconds. These can be changed in the server config.&lt;br /&gt;
&lt;br /&gt;
It is also worth noting that vehicles can only be damaged when there's a player driving them.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== Can I access the black market? =====&lt;br /&gt;
&lt;br /&gt;
No. The black market from singleplayer will not be in the mod. Its functionality will be scriptable using Lua.&lt;br /&gt;
&lt;br /&gt;
In fact, [https://github.com/Philpax/jc2mp-buymenu the buy menu script] is a perfect example of a black market replacement.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== Is the JC2-MP team accepting donations? =====&lt;br /&gt;
&lt;br /&gt;
Yes, we are currently accepting donations to cover hosting costs. [https://www.jc-mp.com/donate/ You can donate here.]&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
== Server Hosting FAQ ==&lt;br /&gt;
&lt;br /&gt;
===== Can LAN-only servers be hosted? =====&lt;br /&gt;
&lt;br /&gt;
Yes, servers can be hosted on a LAN network. Unless your server is exposed to the internet, then it is already LAN-only.&lt;br /&gt;
&lt;br /&gt;
Please note that the LAN tab in the server browser in-game is currently not working properly and you will need to use quick connect.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
===== How do servers handle DLC? =====&lt;br /&gt;
&lt;br /&gt;
It is up to server owners themselves whether to require players to own DLC or not.&lt;br /&gt;
&lt;br /&gt;

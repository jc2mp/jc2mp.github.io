		<title>Server/Getting started/Linux Server</title>
		<link rel="alternate" type="text/html" href="https://wiki.jc-mp.com/Server/Getting_started/Linux_Server"/>
				<updated>2013-12-16T21:52:07Z</updated>
		
		<summary type="html">&lt;p&gt;RedCat: /* Starting up the server in screen */&lt;/p&gt;
&lt;hr /&gt;
&lt;div&gt;Welcome to the JC2-MP Linux server tutorial. This page will explain the very basics of setting up a Linux server. This tutorial assumes you already have some basic Linux knowledge.&lt;br /&gt;
&lt;br /&gt;
==64-bit servers==&lt;br /&gt;
SteamCMD and their libraries are currently 32-bit only, so our server is limited to 32-bit.&lt;br /&gt;
You can still run it on a 64-bit server by installing the required packages shown below.&lt;br /&gt;
&lt;br /&gt;
===Debian, Ubuntu, Mint===&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
dpkg --add-architecture i386&lt;br /&gt;
apt-get update&lt;br /&gt;
apt-get install libc6-i386 lib32gcc1 lib32stdc++6&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
===CentOS, RHEL, Fedora===&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
yum install glibc.i686 libstdc++.i686&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
==Downloading SteamCMD==&lt;br /&gt;
First we need to download SteamCMD. For more information on SteamCMD please [https://developer.valvesoftware.com/wiki/SteamCMD click here]&lt;br /&gt;
&lt;br /&gt;
Login to your server with SSH, then head over to the home directory, we will make our Steam folder there.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
cd /home&lt;br /&gt;
mkdir steam&lt;br /&gt;
cd steam&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
Now we can download SteamCMD and unpack it.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
wget http://media.steampowered.com/client/steamcmd_linux.tar.gz&lt;br /&gt;
tar -xvzf steamcmd_linux.tar.gz&lt;br /&gt;
rm steamcmd_linux.tar.gz&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
==Running SteamCMD and downloading the server==&lt;br /&gt;
Now we need to run SteamCMD.&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
./steamcmd.sh&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
SteamCMD will now update and it might download some files, wait until it finishes.&lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
Then it's time to login with an anonymous Steam account to get access to the server&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
login anonymous&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
Now let's download the latest server version!&lt;br /&gt;
&lt;br /&gt;

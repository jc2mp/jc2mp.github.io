&lt;br /&gt;
&lt;br /&gt;
If you do not have screen installed type:&lt;br /&gt;
&lt;br /&gt;
&amp;lt;syntaxhighlight&amp;gt;&lt;br /&gt;
apt-get install screen&lt;br /&gt;
&amp;lt;/syntaxhighlight&amp;gt;&lt;br /&gt;
&lt;br /&gt;
And follow the instructions. &lt;br /&gt;
&lt;br /&gt;
&lt;br /&gt;
